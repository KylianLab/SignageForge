<?php

declare(strict_types=1);

namespace App\Service;

use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\Component\HttpFoundation\File\UploadedFile;

/**
 * Media files on local disk under {SIGNAGEFORGE_DATA_DIR}/uploads. The database
 * only keeps the generated storage key (the file name). Kept on the local
 * filesystem on purpose: it lets the file route answer HTTP Range requests,
 * which video playback needs. An S3 driver can come later behind this class.
 */
final class MediaStorage
{
    private readonly string $uploadDir;
    private readonly Filesystem $filesystem;

    public function __construct(#[Autowire('%signageforge.data_dir%')] string $dataDir)
    {
        $this->uploadDir = rtrim($dataDir, '/\\').\DIRECTORY_SEPARATOR.'uploads';
        $this->filesystem = new Filesystem();
    }

    /** Moves the upload into storage and returns its storage key. */
    public function store(UploadedFile $file): string
    {
        $this->filesystem->mkdir($this->uploadDir);
        $extension = $file->guessExtension() ?? $file->getClientOriginalExtension();
        $extension = substr(preg_replace('/[^a-z0-9]/i', '', $extension) ?? '', 0, 12);
        $key = bin2hex(random_bytes(16)).('' !== $extension ? '.'.strtolower($extension) : '');
        $file->move($this->uploadDir, $key);

        return $key;
    }

    public function path(string $storageKey): string
    {
        // Storage keys are generated by store(); never let one escape the folder.
        if (basename($storageKey) !== $storageKey) {
            throw new \InvalidArgumentException('Invalid storage key.');
        }

        return $this->uploadDir.\DIRECTORY_SEPARATOR.$storageKey;
    }

    public function exists(string $storageKey): bool
    {
        return is_file($this->path($storageKey));
    }

    public function delete(string $storageKey): void
    {
        $this->filesystem->remove($this->path($storageKey));
    }
}
